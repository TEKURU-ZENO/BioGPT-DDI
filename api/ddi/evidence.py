"""External evidence layer (optional data files).

Two data files can be generated by the scripts in ``scripts/`` and placed in
``DDI_DATA_DIR`` (default: ``api/ddi/data``):

* ``external_ddi.json`` - pair-level severities imported from an external
  database such as DDInter (``scripts/import_ddinter.py``). Used to add
  findings for pairs the curated and mechanism layers do not cover, and to
  flag disagreements.
* ``label_evidence.json`` - Drug Interactions sections of FDA labels fetched
  from openFDA (``scripts/fetch_label_evidence.py``). Used to attach a
  DailyMed link and, where the label text mentions the other drug, a verbatim
  excerpt to each finding (per-claim evidence).

Neither file is required. Without them the engine behaves exactly as before.
External data carries its own licence terms (e.g. DDInter is free for
non-commercial use) and is not committed to this repository.
"""

from __future__ import annotations

import json
import os
import re
from functools import lru_cache
from pathlib import Path
from typing import Dict, List, Optional

DEFAULT_DATA_DIR = Path(__file__).resolve().parent / "data"


def data_dir() -> Path:
    return Path(os.getenv("DDI_DATA_DIR", str(DEFAULT_DATA_DIR)))


def pair_key(a: str, b: str) -> str:
    return "|".join(sorted((a, b)))


@lru_cache(maxsize=1)
def _load(name: str) -> Optional[dict]:
    path = data_dir() / name
    if not path.exists():
        return None
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


def reload() -> None:
    _load.cache_clear()


def external_pair(a: str, b: str) -> Optional[dict]:
    data = _load("external_ddi.json")
    if not data:
        return None
    hit = data.get("pairs", {}).get(pair_key(a, b))
    if hit:
        return {**hit, "source": data.get("source", "external database"), "version": data.get("version")}
    return None


def external_status() -> dict:
    ext, lab = _load("external_ddi.json"), _load("label_evidence.json")
    return {
        "external_ddi": {"loaded": bool(ext), "source": (ext or {}).get("source"),
                         "pairs": len((ext or {}).get("pairs", {}))},
        "label_evidence": {"loaded": bool(lab), "labels": len((lab or {}).get("labels", {}))},
    }


def _label(ingredient: str) -> Optional[dict]:
    data = _load("label_evidence.json")
    if not data:
        return None
    return data.get("labels", {}).get(ingredient)


def _snippet(text: str, term: str, width: int = 220) -> Optional[str]:
    m = re.search(rf"\b{re.escape(term)}\b", text, flags=re.I)
    if not m:
        return None
    start = max(0, m.start() - width // 2)
    end = min(len(text), m.end() + width // 2)
    return ("..." if start else "") + text[start:end].strip() + ("..." if end < len(text) else "")


def label_citations(a: str, b: str, search_terms: Dict[str, List[str]]) -> List[dict]:
    """Label links for both ingredients plus excerpts where one label names the other drug.

    ``search_terms`` maps each ingredient to the names to search for in the
    *other* drug's label (ingredient name, brand names, class words).
    """
    out: List[dict] = []
    for owner, other in ((a, b), (b, a)):
        lab = _label(owner)
        if not lab:
            continue
        entry = {"label_of": owner.title(), "title": lab.get("title"), "url": lab.get("url"),
                 "set_id": lab.get("set_id"), "excerpt": None, "matched_term": None}
        text = lab.get("drug_interactions") or ""
        for term in search_terms.get(other, [other]):
            snip = _snippet(text, term)
            if snip:
                entry["excerpt"], entry["matched_term"] = snip, term
                break
        out.append(entry)
    return out
